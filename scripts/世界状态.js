  // 追加变动描述（去重 + 每键最多保留最近 8 条）
  function pushNote(map, key, text) {
    if (!key || !text) return;
    const arr = Array.isArray(map[key]) ? map[key] : (map[key] = []);
    if (arr.includes(text)) return;
    arr.push(text);
    if (arr.length > 8) arr.splice(0, arr.length - 8);
  }

