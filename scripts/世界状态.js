  // 圣光历日期 → 连续月数（与纪元触发器 _pn 同口径）；解析失败返回 0
  function parseMonth(dateStr) {
    const m = String(dateStr || '').match(/圣光历(\d+)年(?:\s*(\d+)月)?/);
    if (!m) return 0;
    return parseInt(m[1], 10) * 12 + (m[2] ? parseInt(m[2], 10) : 1);
  }

  // ---- 后果结算（白名单校验 → 应用 → 路由）----
  function applyConsequence(ws, hg, title, nowMonth) {
    const 类型 = String(hg.类型 || '').trim();
    const 目标 = String(hg.目标 || '').trim();
    const 新值 = String(hg.新值 || '').trim();
    if (!ALLOWED_TYPES.includes(类型)) {
      console.warn('[世界状态] 忽略未知后果类型（防幻觉护栏）:', 类型, '（新闻：' + title + '）');
      return false;
    }
    if (!目标) {
      console.warn('[世界状态] 忽略无目标的后果申报:', 类型, '（新闻：' + title + '）');
      return false;
    }
    switch (类型) {
      case '据点易手':
        ws.势力控制[目标] = 新值 || '未知势力';
        pushNote(ws.地点变动, routeLoc(目标), `${目标}已易手，现由${新值 || '未知势力'}控制`);
        pushNote(ws.势力变动, routeFac(新值) || routeFac(目标), `${目标}落入${新值 || '未知势力'}之手`);
        break;
      case '据点毁灭':
        ws.据点存续[目标] = false;
        pushNote(ws.地点变动, routeLoc(目标), `${目标}已被摧毁/消失${新值 ? '（' + 新值 + '）' : ''}`);
        break;
      case '人物死亡':
        ws.人物命运[目标] = '死亡' + (新值 ? '（' + 新值 + '）' : '');
        pushNote(ws.地点变动, routeLoc(目标), `${目标}已死亡${新值 ? '：' + 新值 : ''}`);
        pushNote(ws.势力变动, routeFac(目标), `${目标}已死亡${新值 ? '：' + 新值 : ''}`);
        break;
      case '人物下台':
        ws.人物命运[目标] = 新值 || '下台';
        pushNote(ws.势力变动, routeFac(目标), `${目标}已下台${新值 ? '：' + 新值 : ''}`);
        break;
      case '事件阻止':
        ws.事件旗标[目标] = { 状态: '已阻止', 月: nowMonth, 说明: 新值 };
        break;
      case '事件提前':
        ws.事件旗标[目标] = { 状态: '已提前', 月: parseMonth(新值) || nowMonth, 说明: 新值 };
        break;
      case '事件结束':
        ws.事件旗标[目标] = { 状态: '已结束', 月: nowMonth, 说明: 新值 };
        break;
      case '势力变动':
        pushNote(ws.势力变动, routeFac(目标) || 目标, 新值 || title);
        pushNote(ws.地点变动, routeLoc(目标), 新值 || title);
        break;
    }
    console.log(`[世界状态] 结算后果「${title}」：${类型} → ${目标}${新值 ? ' = ' + 新值 : ''}`);
    return true;
  }

